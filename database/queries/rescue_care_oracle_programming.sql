-- 医疗记录插入后触发器：按主分支 MedRecordTypes 契约自动生成后续提醒。
CREATE OR REPLACE TRIGGER TRG_HEALTHRECORDS_AI_REMINDER
AFTER INSERT ON MED_HEALTHRECORDS
FOR EACH ROW
DECLARE
    V_REMINDERTYPE MED_REMINDERS.REMINDERTYPE%TYPE;
BEGIN
    IF :NEW.NEXTDUEDATE IS NULL THEN
        RETURN;
    END IF;

    V_REMINDERTYPE :=
        CASE UPPER(:NEW.RECORDTYPE)
            WHEN 'VACCINATION' THEN 'VACCINATION'
            WHEN 'DEWORMING' THEN 'DEWORMING'
            WHEN 'SURGERY' THEN 'SURGERY'
            WHEN 'CHECKUP' THEN 'CHECKUP'
            WHEN 'TREATMENT' THEN 'TREATMENT'
            WHEN 'EMERGENCY' THEN 'EMERGENCY'
            ELSE 'OTHER'
        END;

    INSERT INTO MED_REMINDERS (
        REMINDERID,
        RECORDID,
        CATID,
        REMINDERTYPE,
        REMINDERTIME,
        SENDSTATUS
    ) VALUES (
        LOWER(RAWTOHEX(SYS_GUID())),
        :NEW.RECORDID,
        :NEW.CATID,
        V_REMINDERTYPE,
        :NEW.NEXTDUEDATE,
        'PENDING'
    );
END;
