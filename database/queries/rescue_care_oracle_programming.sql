CREATE OR REPLACE PACKAGE BODY PKG_RESCUE_CARE AS
    FUNCTION NEW_ID RETURN VARCHAR2 AS
    BEGIN
        RETURN LOWER(RAWTOHEX(SYS_GUID()));
    END NEW_ID;

    PROCEDURE ASSERT_NOT_BLANK(P_VALUE IN VARCHAR2, P_ERROR_CODE IN NUMBER, P_ERROR_MESSAGE IN VARCHAR2) AS
    BEGIN
        IF P_VALUE IS NULL OR TRIM(P_VALUE) IS NULL THEN
            RAISE_APPLICATION_ERROR(P_ERROR_CODE, P_ERROR_MESSAGE);
        END IF;
    END ASSERT_NOT_BLANK;

    PROCEDURE ASSERT_STATUS(P_VALUE IN VARCHAR2, P_ALLOWED IN VARCHAR2, P_ERROR_CODE IN NUMBER, P_ERROR_MESSAGE IN VARCHAR2) AS
    BEGIN
        IF P_VALUE IS NULL OR INSTR(',' || P_ALLOWED || ',', ',' || P_VALUE || ',') = 0 THEN
            RAISE_APPLICATION_ERROR(P_ERROR_CODE, P_ERROR_MESSAGE || ': ' || NVL(P_VALUE, '<NULL>'));
        END IF;
    END ASSERT_STATUS;

    PROCEDURE CREATE_REMINDER(
        P_RECORDID       IN MED_REMINDERS.RECORDID%TYPE,
        P_CATID          IN MED_REMINDERS.CATID%TYPE,
        P_REMINDERTYPE   IN MED_REMINDERS.REMINDERTYPE%TYPE,
        P_RECEIVERUSERID IN MED_REMINDERS.RECEIVERUSERID%TYPE,
        P_REMINDERTIME   IN MED_REMINDERS.REMINDERTIME%TYPE,
        O_REMINDERID     OUT MED_REMINDERS.REMINDERID%TYPE
    ) AS
        V_RECORD_COUNT NUMBER;
    BEGIN
        ASSERT_NOT_BLANK(P_CATID, -20120, 'Cat id is required');
        ASSERT_NOT_BLANK(P_REMINDERTYPE, -20121, 'Reminder type is required');

        IF P_RECORDID IS NOT NULL THEN
            SELECT COUNT(1) INTO V_RECORD_COUNT
            FROM MED_HEALTHRECORDS
            WHERE RECORDID = P_RECORDID AND CATID = P_CATID;
            IF V_RECORD_COUNT = 0 THEN
                RAISE_APPLICATION_ERROR(-20128, 'Medical record does not belong to the specified cat');
            END IF;
        END IF;

        IF P_REMINDERTIME IS NULL THEN
            RAISE_APPLICATION_ERROR(-20122, 'Reminder time is required');
        END IF;

        ASSERT_STATUS(
            UPPER(P_REMINDERTYPE),
            'VACCINATION,CHECKUP,TREATMENT,SURGERY,DEWORMING,EMERGENCY,OTHER',
            -20123,
            'Invalid reminder type'
        );

        O_REMINDERID := NEW_ID();

        INSERT INTO MED_REMINDERS (
            REMINDERID,
            RECORDID,
            CATID,
            REMINDERTYPE,
            RECEIVERUSERID,
            REMINDERTIME,
            SENDSTATUS
        ) VALUES (
            O_REMINDERID,
            P_RECORDID,
            P_CATID,
            UPPER(P_REMINDERTYPE),
            P_RECEIVERUSERID,
            P_REMINDERTIME,
            'PENDING'
        );
    END CREATE_REMINDER;

    PROCEDURE MARK_REMINDER_SENT(P_REMINDERID IN MED_REMINDERS.REMINDERID%TYPE) AS
    BEGIN
        ASSERT_NOT_BLANK(P_REMINDERID, -20124, 'Reminder id is required');

        UPDATE MED_REMINDERS
        SET SENDSTATUS = 'SENT'
        WHERE REMINDERID = P_REMINDERID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20125, 'Reminder not found');
        END IF;
    END MARK_REMINDER_SENT;

