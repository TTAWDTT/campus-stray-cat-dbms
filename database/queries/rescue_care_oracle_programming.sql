-- 失踪预警更新前触发器：统一状态，并在寻回或关闭时自动补关闭时间。
CREATE OR REPLACE TRIGGER TRG_CAT_MISSINGALERTS_BU
BEFORE UPDATE ON CAT_MISSINGALERTS
FOR EACH ROW
BEGIN
    IF :NEW.ALERTSTATUS IS NOT NULL THEN
        :NEW.ALERTSTATUS := UPPER(:NEW.ALERTSTATUS);
    END IF;

    IF :NEW.ALERTSTATUS IN ('FOUND', 'CLOSED') AND :NEW.CLOSETIME IS NULL THEN
        :NEW.CLOSETIME := SYSDATE;
    END IF;
END;
