        UPDATE MED_REMINDERS
        SET SENDSTATUS = 'COMPLETED'
        WHERE REMINDERID = P_REMINDERID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20127, 'Reminder not found');
        END IF;
    END COMPLETE_REMINDER;

