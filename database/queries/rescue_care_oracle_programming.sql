-- 医疗提醒插入前触发器：补 ID，并统一提醒类型和发送状态。
CREATE OR REPLACE TRIGGER TRG_MED_REMINDERS_BI
BEFORE INSERT ON MED_REMINDERS
FOR EACH ROW
BEGIN
    IF :NEW.REMINDERID IS NULL THEN
        :NEW.REMINDERID := LOWER(RAWTOHEX(SYS_GUID()));
    END IF;

    :NEW.REMINDERTYPE := UPPER(:NEW.REMINDERTYPE);
    :NEW.SENDSTATUS := UPPER(NVL(:NEW.SENDSTATUS, 'PENDING'));
END;
/

-- 医疗提醒更新前触发器：防止大小写不一致影响查询。
CREATE OR REPLACE TRIGGER TRG_MED_REMINDERS_BU
BEFORE UPDATE ON MED_REMINDERS
FOR EACH ROW
BEGIN
    :NEW.REMINDERTYPE := UPPER(:NEW.REMINDERTYPE);
    :NEW.SENDSTATUS := UPPER(:NEW.SENDSTATUS);
END;
/

-- 紧急救助上报插入前触发器：补 ID、上报时间、默认状态，并统一枚举大小写。
CREATE OR REPLACE TRIGGER TRG_EMERGENCY_REPORTS_BI
BEFORE INSERT ON EMERGENCY_REPORTS
FOR EACH ROW
BEGIN
    IF :NEW.REPORTID IS NULL THEN
        :NEW.REPORTID := LOWER(RAWTOHEX(SYS_GUID()));
    END IF;

