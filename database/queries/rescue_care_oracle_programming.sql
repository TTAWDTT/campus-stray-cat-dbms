    PROCEDURE CREATE_MISSING_ALERT(
        P_CATID            IN CAT_MISSINGALERTS.CATID%TYPE,
        P_LASTSIGHTINGID   IN CAT_MISSINGALERTS.LASTSIGHTINGID%TYPE,
        P_LASTSIGHTINGTIME IN CAT_MISSINGALERTS.LASTSIGHTINGTIME%TYPE,
        P_THRESHOLDDAYS    IN CAT_MISSINGALERTS.THRESHOLDDAYS%TYPE,
        P_HANDLERUSERID    IN CAT_MISSINGALERTS.HANDLERUSERID%TYPE,
        P_REMARK           IN CAT_MISSINGALERTS.REMARK%TYPE,
        O_ALERTID          OUT CAT_MISSINGALERTS.ALERTID%TYPE
    ) AS
        V_SIGHTING_COUNT NUMBER;
        V_ACTIVE_ALERT_COUNT NUMBER;
    BEGIN
        ASSERT_NOT_BLANK(P_CATID, -20160, 'Cat id is required');

        IF P_LASTSIGHTINGID IS NOT NULL THEN
            SELECT COUNT(1) INTO V_SIGHTING_COUNT
            FROM CAT_SIGHTINGS
            WHERE SIGHTINGID = P_LASTSIGHTINGID AND CATID = P_CATID;
            IF V_SIGHTING_COUNT = 0 THEN
                RAISE_APPLICATION_ERROR(-20162, 'Last sighting does not belong to the specified cat');
            END IF;
        END IF;

        SELECT COUNT(1) INTO V_ACTIVE_ALERT_COUNT
        FROM CAT_MISSINGALERTS
        WHERE CATID = P_CATID AND UPPER(ALERTSTATUS) = 'PROCESSING';
        IF V_ACTIVE_ALERT_COUNT > 0 THEN
            RAISE_APPLICATION_ERROR(-20163, 'The cat already has an active missing alert');
        END IF;

        IF P_THRESHOLDDAYS IS NOT NULL AND P_THRESHOLDDAYS <= 0 THEN
            RAISE_APPLICATION_ERROR(-20161, 'Threshold days must be greater than 0');
        END IF;

        O_ALERTID := NEW_ID();

        INSERT INTO CAT_MISSINGALERTS (
            ALERTID,
            CATID,
            LASTSIGHTINGID,
            LASTSIGHTINGTIME,
            THRESHOLDDAYS,
            ALERTTIME,
            ALERTSTATUS,
            HANDLERUSERID,
            REMARK
        ) VALUES (
            O_ALERTID,
            P_CATID,
            P_LASTSIGHTINGID,
            P_LASTSIGHTINGTIME,
            P_THRESHOLDDAYS,
            SYSDATE,
            'PROCESSING',
            P_HANDLERUSERID,
            P_REMARK
        );
    END CREATE_MISSING_ALERT;

    PROCEDURE UPDATE_MISSING_STATUS(
        P_ALERTID       IN CAT_MISSINGALERTS.ALERTID%TYPE,
        P_ALERTSTATUS   IN CAT_MISSINGALERTS.ALERTSTATUS%TYPE,
        P_HANDLERUSERID IN CAT_MISSINGALERTS.HANDLERUSERID%TYPE,
        P_REMARK        IN CAT_MISSINGALERTS.REMARK%TYPE
    ) AS
    BEGIN
        ASSERT_NOT_BLANK(P_ALERTID, -20170, 'Missing alert id is required');
        ASSERT_NOT_BLANK(P_ALERTSTATUS, -20171, 'Missing alert status is required');
        ASSERT_NOT_BLANK(P_HANDLERUSERID, -20172, 'Handler user id is required');
        ASSERT_STATUS(UPPER(P_ALERTSTATUS), 'PROCESSING,FOUND,CLOSED', -20173, 'Invalid missing alert status');

        UPDATE CAT_MISSINGALERTS
        SET ALERTSTATUS = UPPER(P_ALERTSTATUS),
            HANDLERUSERID = P_HANDLERUSERID,
            REMARK = NVL(P_REMARK, REMARK),
            CLOSETIME = CASE
                WHEN UPPER(P_ALERTSTATUS) IN ('FOUND', 'CLOSED') THEN SYSDATE
                ELSE CLOSETIME
            END
        WHERE ALERTID = P_ALERTID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20174, 'Missing alert not found');
        END IF;
    END UPDATE_MISSING_STATUS;

    PROCEDURE AUTO_CREATE_REMINDERS_FROM_HEALTH AS
    BEGIN
        INSERT INTO MED_REMINDERS (
            REMINDERID,
            RECORDID,
            CATID,
            REMINDERTYPE,
            REMINDERTIME,
            SENDSTATUS
        )
        SELECT LOWER(RAWTOHEX(SYS_GUID())),
               H.RECORDID,
               H.CATID,
               CASE UPPER(H.RECORDTYPE)
                   WHEN 'VACCINATION' THEN 'VACCINATION'
                   WHEN 'DEWORMING' THEN 'DEWORMING'
                   WHEN 'SURGERY' THEN 'SURGERY'
                   WHEN 'CHECKUP' THEN 'CHECKUP'
                   WHEN 'TREATMENT' THEN 'TREATMENT'
                   WHEN 'EMERGENCY' THEN 'EMERGENCY'
                   ELSE 'OTHER'
               END,
               H.NEXTDUEDATE,
               'PENDING'
        FROM MED_HEALTHRECORDS H
        WHERE H.NEXTDUEDATE IS NOT NULL
          AND NOT EXISTS (
              SELECT 1
              FROM MED_REMINDERS R
              WHERE R.RECORDID = H.RECORDID
          );
    END AUTO_CREATE_REMINDERS_FROM_HEALTH;
