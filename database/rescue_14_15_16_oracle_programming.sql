        P_THRESHOLDDAYS     IN CAT_MISSINGALERTS.THRESHOLDDAYS%TYPE,
        P_HANDLERUSERID     IN CAT_MISSINGALERTS.HANDLERUSERID%TYPE,
        P_REMARK            IN CAT_MISSINGALERTS.REMARK%TYPE,
        O_ALERTID           OUT CAT_MISSINGALERTS.ALERTID%TYPE
    ) AS
    BEGIN
        -- 阈值天数不能为负数或 0，防止创建无意义的预警。
        IF P_THRESHOLDDAYS IS NOT NULL AND P_THRESHOLDDAYS <= 0 THEN
            RAISE_APPLICATION_ERROR(-20109, '阈值天数必须大于 0');
        END IF;

        -- 生成失踪预警，默认状态是 PROCESSING。
        O_ALERTID := NEW_ID();

        INSERT INTO CAT_MISSINGALERTS (
            ALERTID,
            CATID,
            LASTSIGHTINGID,
            LASTSIGHTINGTIME,
            THRESHOLDDAYS,
            ALERTTIME,
            ALERTSTATUS,
            HANDLERUSERID,
            CLOSETIME,
            REMARK
        ) VALUES (
            O_ALERTID,
            P_CATID,
            P_LASTSIGHTINGID,
            P_LASTSIGHTINGTIME,
            NVL(P_THRESHOLDDAYS, 7),
            SYSDATE,
            'PROCESSING',
            P_HANDLERUSERID,
            NULL,
            P_REMARK
        );
    END CREATE_MISSING_ALERT;

    -- 16. 更新失踪预警状态，支持处理中、已寻回、已关闭。
    PROCEDURE UPDATE_MISSING_STATUS(
        P_ALERTID       IN CAT_MISSINGALERTS.ALERTID%TYPE,
        P_ALERTSTATUS   IN CAT_MISSINGALERTS.ALERTSTATUS%TYPE,
        P_HANDLERUSERID IN CAT_MISSINGALERTS.HANDLERUSERID%TYPE,
        P_REMARK        IN CAT_MISSINGALERTS.REMARK%TYPE
    ) AS
    BEGIN
        -- 校验状态后再更新，确保只能流转到允许的预警状态。
        ASSERT_STATUS(
            UPPER(P_ALERTSTATUS),
            'PROCESSING,FOUND,CLOSED',
            -20107,
            '失踪预警状态必须是 PROCESSING, FOUND, CLOSED 之一'
        );

        UPDATE CAT_MISSINGALERTS
        SET ALERTSTATUS = UPPER(P_ALERTSTATUS),
            HANDLERUSERID = NVL(P_HANDLERUSERID, HANDLERUSERID),
            CLOSETIME = CASE
                WHEN UPPER(P_ALERTSTATUS) IN ('FOUND', 'CLOSED') THEN SYSDATE
                ELSE CLOSETIME
            END,
            REMARK = P_REMARK
        WHERE ALERTID = P_ALERTID;

        IF SQL%ROWCOUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20108, '失踪预警不存在');
        END IF;
    END UPDATE_MISSING_STATUS;

    -- 批处理：根据医疗记录补生成提醒，防止漏掉后续护理事项。
    PROCEDURE AUTO_CREATE_REMINDERS_FROM_HEALTH AS
    BEGIN
        -- 扫描医疗记录，给存在下次处理日期的记录自动补生成提醒。
        INSERT INTO MED_REMINDERS (
            REMINDERID,
            RECORDID,
            CATID,
            REMINDERTYPE,
            RECEIVERUSERID,
            REMINDERTIME,
            SENDSTATUS
        )
        SELECT
            LOWER(RAWTOHEX(SYS_GUID())),
            H.RECORDID,
            H.CATID,
            CASE
                WHEN UPPER(H.RECORDTYPE) IN ('VACCINE', 'DEWORM', 'STERILIZATION')
                THEN UPPER(H.RECORDTYPE)
                ELSE 'RECHECK'
            END,
            NULL,
            H.NEXTDUEDATE,
            'PENDING'
        FROM MED_HEALTHRECORDS H
        WHERE H.NEXTDUEDATE IS NOT NULL
          AND NOT EXISTS (
              SELECT 1
              FROM MED_REMINDERS R
              WHERE R.RECORDID = H.RECORDID
                AND R.REMINDERTYPE =
                    CASE
                        WHEN UPPER(H.RECORDTYPE) IN ('VACCINE', 'DEWORM', 'STERILIZATION')
                        THEN UPPER(H.RECORDTYPE)
                        ELSE 'RECHECK'
                    END
          );
    END AUTO_CREATE_REMINDERS_FROM_HEALTH;

