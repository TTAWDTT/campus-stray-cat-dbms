-- TRG_MED_HEALTHRECORDS_AUTO_REMINDER：插入或更新医疗记录时，如果存在下次处理日期，就自动生成后续提醒。
CREATE OR REPLACE TRIGGER TRG_MED_HEALTHRECORDS_AUTO_REMINDER
AFTER INSERT OR UPDATE OF NEXTDUEDATE, RECORDTYPE ON MED_HEALTHRECORDS
FOR EACH ROW
DECLARE
    V_REMINDERTYPE MED_REMINDERS.REMINDERTYPE%TYPE;
    V_EXISTS NUMBER;
BEGIN
    IF :NEW.NEXTDUEDATE IS NULL THEN
        RETURN;
    END IF;

    V_REMINDERTYPE :=
        CASE
            WHEN UPPER(:NEW.RECORDTYPE) IN ('VACCINE', 'DEWORM', 'STERILIZATION')
            THEN UPPER(:NEW.RECORDTYPE)
            ELSE 'RECHECK'
        END;

    SELECT COUNT(*)
    INTO V_EXISTS
    FROM MED_REMINDERS
    WHERE RECORDID = :NEW.RECORDID
      AND REMINDERTYPE = V_REMINDERTYPE;

    IF V_EXISTS = 0 THEN
        INSERT INTO MED_REMINDERS (
            REMINDERID,
            RECORDID,
            CATID,
            REMINDERTYPE,
            RECEIVERUSERID,
            REMINDERTIME,
            SENDSTATUS
        ) VALUES (
            LOWER(RAWTOHEX(SYS_GUID())),
            :NEW.RECORDID,
            :NEW.CATID,
            V_REMINDERTYPE,
            NULL,
            :NEW.NEXTDUEDATE,
            'PENDING'
        );
    END IF;
END;
